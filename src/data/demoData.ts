/**
 * The demo account.
 *
 * A fictional recent graduate with a biweekly paycheck, a fixed set of monthly
 * bills, irregular grocery and coffee spending, a small monthly transfer from
 * family, and a couple of one-off purchases.
 *
 * The dataset is generated RELATIVE TO TODAY (about 95 days of history ending
 * yesterday) so the demo never expires. It is ordinary transaction data: it
 * carries no predictions, no labels and no expected results. Everything the
 * forecast screen shows is derived by the same detection and forecast code that
 * runs on an uploaded CSV — nothing about the demo is hard-coded downstream.
 *
 * Recurring bills are anchored by HOW MANY DAYS UNTIL THEIR NEXT OCCURRENCE
 * rather than by a fixed day of the month, and the paycheck is anchored so the
 * next payday is 13 days out. That keeps the demonstration stable: whatever day
 * the demo is opened, the same obligations fall between today and payday, so
 * the projected low point is the same story every time.
 *
 * The amounts and offsets are the only thing tuned here. The forecast itself is
 * whatever the detectors and the forecast engine make of this history.
 */

