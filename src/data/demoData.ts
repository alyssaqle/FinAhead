/** Biweekly paycheck. Net pay moves a little with hours, well inside the 20% band. */
const PAYROLL_MERCHANT = 'NORTHGATE UNIV PAYROLL'
const PAYROLL_AMOUNTS = [1412.55, 1398.2, 1421.08, 1412.55, 1405.6, 1412.55, 1398.2]

/** Days between paydays, and how long ago the most recent one landed. */
const PAYROLL_INTERVAL_DAYS = 14
const DAYS_SINCE_LAST_PAYDAY = 1

/**
 * Days from the as-of date to the next paycheck, and therefore to the end of
 * the forecast window. Every bill above with a smaller offset lands before it.
 */
export const PAYDAY_IN_DAYS = PAYROLL_INTERVAL_DAYS - DAYS_SINCE_LAST_PAYDAY

export interface DemoDataset {
  transactions: Transaction[]
  currentBalance: number
  asOfDate: string
  /** First date covered by the generated history. */
  historyStartDate: string
}

/**
 * The historical occurrences of a monthly bill, oldest first.
 *
 * Stepping back whole calendar months from the next-occurrence anchor keeps the
 * day of the month stable, which is how real billers behave. Month-end clamping
 * can pull the projected next date a day or two earlier than the anchor, never
 * later, so a bill anchored inside the window stays inside it.
 */
function monthlyHistory(anchorDate: string, count: number): string[] {
  const dates: string[] = []
  for (let monthsBack = count; monthsBack >= 1; monthsBack -= 1) {
    dates.push(addMonthsClamped(anchorDate, -monthsBack))
  }
  return dates
}

/**
 * Build the demo account as of `asOfDate` (defaults to today).
 *
 * The output is plain transaction history. Run it through the same detectors
 * and forecast engine as any uploaded file to see the projection.
 */
export function buildDemoDataset(asOfDate: string): DemoDataset {
  const historyStartDate = addDays(asOfDate, -DEMO_HISTORY_DAYS)
  const lastHistoryDate = addDays(asOfDate, -1)
  const rows: Omit<Transaction, 'id'>[] = []

  // Paychecks, walking backwards from the most recent one.
  let payday = addDays(asOfDate, -DAYS_SINCE_LAST_PAYDAY)
  for (let index = 0; payday >= historyStartDate; index += 1) {
    rows.push({
      date: payday,
      merchant: PAYROLL_MERCHANT,
      amount: PAYROLL_AMOUNTS[index % PAYROLL_AMOUNTS.length],
      category: 'Income',
    })
    payday = addDays(payday, -PAYROLL_INTERVAL_DAYS)
  }

  // Fixed monthly bills and the monthly transfer.
  for (const charge of MONTHLY_CHARGES) {
    const anchor = addDays(asOfDate, charge.daysUntilNext)
    monthlyHistory(anchor, MONTHLY_HISTORY_COUNT).forEach((date, index) => {
      rows.push({
        date,
        merchant: charge.merchant,
        amount: charge.amounts[index % charge.amounts.length],
        category: charge.category,
      })
    })
  }

  // Everyday and one-off spending.
  for (const charge of ONE_OFF_CHARGES) {
    rows.push({
      date: addDays(asOfDate, -charge.daysAgo),
      merchant: charge.merchant,
      amount: charge.amount,
      category: charge.category,
    })
  }

  const sorted = rows
    .filter((row) => row.date >= historyStartDate && row.date <= lastHistoryDate)
    .sort((a, b) =>
      a.date === b.date
        ? a.merchant.localeCompare(b.merchant)
        : a.date < b.date
          ? -1
          : 1,
    )

  return {
    transactions: sorted.map((row, index) => ({ ...row, id: `demo-${index + 1}` })),
    currentBalance: DEMO_STARTING_BALANCE,
    asOfDate,
    historyStartDate,
  }
}
